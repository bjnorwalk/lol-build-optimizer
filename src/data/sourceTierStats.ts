export const sourceCheckedTierRows: SourceTierStatRow[] = parseSourceTierRows(sourceTierRaw);

export function getSourceTierStat(championName: string, role: Role) {
  const normalizedChampion = normalizeName(championName);
  return sourceCheckedTierRows.find((row) => normalizeName(row.championName) === normalizedChampion && row.role === role);
}

function parseSourceTierRows(raw: string): SourceTierStatRow[] {
  const lines = raw
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);

  const rows: SourceTierStatRow[] = [];
  for (let index = 0; index < lines.length; index += 8) {
    const [rank, role, championName, tier, winRate, pickRate, banRate, matches] = lines.slice(index, index + 8);
    if (!matches) continue;
    rows.push({
      rank: Number(rank),
      role: parseRole(role),
      championName,
      tier,
      winRate: parsePercent(winRate),
      pickRate: parsePercent(pickRate),
      banRate: parsePercent(banRate),
      matches: Number(matches.replace(/,/g, ''))
    });
  }
  return rows;
}

function parseRole(value: string): Role {
  const normalized = value.toLowerCase();
  if (normalized === 'top') return 'Top';
  if (normalized === 'jungle') return 'Jungle';
  if (normalized === 'mid') return 'Mid';
  if (normalized === 'adc') return 'ADC';
  return 'Support';
}

function parsePercent(value: string) {
  return Number(value.replace('%', ''));
}

function normalizeName(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]/g, '');
}
