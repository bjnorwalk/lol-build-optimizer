export const requiredChampionCount = requiredChampionNames.length;

export function findMissingRequiredChampions(champions: Champion[]) {
  const available = new Set(champions.map((champion) => normalizeChampionName(champion.name)));
  return requiredChampionNames.filter((name) => !available.has(normalizeChampionName(name)));
}

export function championBuildSlug(champion: Champion) {
  return champion.name
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/['.]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function normalizeChampionName(name: string) {
  return name.toLowerCase().replace(/[^a-z0-9]/g, '');
}
